'use strict';
const assert=require('node:assert/strict'),{test}=require('node:test'),{mkdtempSync,rmSync,readFileSync}=require('node:fs'),{tmpdir}=require('node:os'),{join}=require('node:path');
const {openStore}=require('../src/v3/service/store.cjs'),{digest}=require('../src/v3/service/adapter-sdk.cjs');
test('External tool versions require probe and enable, freeze approval, dispatch once, preserve advice and reject upgraded pending jobs',t=>{
 const root=mkdtempSync(join(tmpdir(),'cd-ext-')),s=openStore(root);t.after(()=>{s.close();rmSync(root,{recursive:true,force:true});});
 const manifest=JSON.parse(readFileSync('examples/dsh-cutdirector-report/manifest.json','utf8')),id=manifest.pluginId;
 const first=s.extensions.register({toolName:'cutdirector_adapter_local_rhythm_report__1_0_0',manifest,confirm:true});
 s.extensions.select({pluginId:id,version:'1.0.0',expectedDigest:null,confirm:true});
 let entry=s.registry.list().find(row=>row.manifest.pluginId===id);
 assert.equal(entry.enabled,false);assert.throws(()=>s.registry.configure({pluginId:id,expectedVersion:entry.version,enabled:true,confirm:true}),{code:'PLUGIN_PROBE_REQUIRED'});
 s.registry.probe(id,{available:true,message:'local'});
 s.registry.configure({pluginId:id,expectedVersion:entry.version,enabled:true,confirm:true});
 const p=s.mutate('project',{commandId:'p',title:'Extension',kind:'idea'}),other=s.mutate('project',{commandId:'o',title:'Other',kind:'idea'});
 const job=s.extensions.prepare(p.id,{commandId:'job',pluginId:id,text:'检查时长',includeStory:false,includeMedia:false});
 assert.equal(job.state,'awaiting_approval');assert.equal(job.snapshot.story,undefined);
 assert.throws(()=>s.extensions.claim(p.id,job.id,{confirm:true,snapshotDigest:'bad'}),{code:'EXTENSION_APPROVAL_REQUIRED'});
 const claim=s.extensions.claim(p.id,job.id,{confirm:true,snapshotDigest:job.snapshotDigest});assert.equal(claim.dispatch,true);
 assert.equal(s.extensions.claim(p.id,job.id,{confirm:true,snapshotDigest:job.snapshotDigest}).dispatch,false);
 s.extensions.finish(p.id,job.id,{ok:true,result:{text:'本地建议'}});
 assert.equal(s.extensions.jobs(p.id)[0].result.advisoryOnly,true);
 assert.throws(()=>s.extensions.job(other.id,job.id),{code:'TASK_NOT_FOUND'});
 const pending=s.extensions.prepare(p.id,{commandId:'pending',pluginId:id,text:'稍后分析'});
 s.extensions.register({toolName:'cutdirector_adapter_local_rhythm_report__1_1_0',manifest:{...manifest,version:'1.1.0'},confirm:true});
 s.extensions.select({pluginId:id,version:'1.1.0',expectedDigest:first.digest,confirm:true});
 entry=s.registry.list().find(row=>row.manifest.pluginId===id);assert.equal(entry.enabled,false);
 s.registry.probe(id,{available:true});s.registry.configure({pluginId:id,expectedVersion:entry.version,enabled:true,confirm:true});
 assert.throws(()=>s.extensions.claim(p.id,pending.id,{confirm:true,snapshotDigest:digest(pending.snapshot)}),{code:'EXTENSION_CHANGED'});
 assert.equal(s.extensions.jobs(p.id).find(row=>row.id===job.id).result.text,'本地建议');
 assert.equal(s.activity.summary(p.id).finished,1);
});
